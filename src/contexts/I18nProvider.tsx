// Helper to get nested value from object by string path
const getNestedTranslation = (translations: Translations, key: string): string | undefined => {
    return key.split('.').reduce((obj: any, k) => {
        if (obj && typeof obj === 'object' && k in obj) {
            return obj[k];
        }
        return undefined;
    }, translations as any) as string | undefined;
};

