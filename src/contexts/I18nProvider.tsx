export const I18nProvider: React.FC<{ children: ReactNode }> = ({ children }) => {
    const [locale, setLocale] = useState<Locale>(() => {
        const storedLocale = localStorage.getItem('locale') as Locale;
        if (storedLocale && ['en', 'es'].includes(storedLocale)) {
            return storedLocale;
        }
        const browserLang = navigator.language.split('-')[0];
        return browserLang === 'es' ? 'es' : 'en';
    });

    useEffect(() => {
        document.documentElement.lang = locale;
    }, [locale]);

    const changeLocale = useCallback((newLocale: Locale) => {
        setLocale(newLocale);
        localStorage.setItem('locale', newLocale);
        document.documentElement.lang = newLocale;
    }, []);

    const t = useCallback((key: string, variables?: { [key: string]: string | number }) => {
        const currentDict = translationsMap[locale] || translationsMap['es'];
        let translation = getNestedTranslation(currentDict, key);

        if (!translation && locale !== 'es') {
            translation = getNestedTranslation(translationsMap['es'], key);
        }

        if (!translation) {
            return key;
        }

        if (variables) {
            Object.keys(variables).forEach(varName => {
                const regex = new RegExp(`\\{\\{\\s*${varName}\\s*\\}\\}`, 'g');
                translation = (translation as string).replace(regex, String(variables[varName]));
            });
        }
        
        return translation;
    }, [locale]);

    const value = { locale, changeLocale, t };

    return (
        <I18nContext.Provider value={value}>
            {children}
        </I18nContext.Provider>
    );
};